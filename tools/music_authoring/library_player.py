"""Single offline library player for every example song (ATMlib2FX-3ii.12).

``python3 tools/music_authoring/library_player.py --catalog CATALOG.json \
    --out examples/music_authoring/player.html --json``

The bundler reads a local JSON catalog of songs (source ``song.json`` path plus a
``render``/``preview`` directory holding the matching ``preview.json`` +
``preview.wav``), and for each song rebuilds the **canonical standalone review
HTML** using the existing frontend: ``load_and_validate`` -> ``lower`` ->
``build_review_payload`` -> ``load_audio_preview`` -> ``build_inspect_document``
-> ``render_html``.  It then embeds those complete review documents in one inert
JSON bundle inside a small shell page (``player.html``) that mounts exactly one
review iframe on selection.

The song sources live with their examples (``examples/music_authoring/**``); the
matching ``preview.json`` + ``preview.wav`` music files are promoted out of the
git-ignored ``build/`` tree and maintained in each song's
``examples/music_authoring/**/preview/`` directory. The shell assets
(``template.html``, ``shell.css``, ``shell.js``) live beside this tool.

Design constraints:

* **Offline / self-contained.** The output embeds everything (viewer CSS/JS,
  canonical payloads and base64 WAVs) as inert data; it needs no server, network,
  CDN, sibling file or ``build/`` directory.
* **No divergent viewer.** The embedded documents are produced by the same
  ``render_html`` the ``inspect`` command uses; the shell copies no timeline or
  audio logic.  Selection swaps one iframe by ``srcdoc``; there is never more
  than one live review/audio element, and nothing autoplays.
* **Escape-safe.** The bundle goes through ``serialize_embedded_json`` (escapes
  ``<``, ``>``, ``&`` and U+2028/2029), so embedded ``</script>`` sequences stay
  inert.
* **Host-only.** Nothing here changes AVR runtime, SRAM, flash or the FX backend.

The catalog and the referenced sources/previews are **trusted local inputs**;
this tool renders authored strings as inert text but does not sandbox arbitrary
untrusted HTML.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

# This module lives inside the ``music_authoring`` package directory, so running
# it as a script would put that directory on ``sys.path[0]`` and shadow the
# standard-library ``inspect`` module that ``dataclasses`` imports (the package
# also ships an ``inspect.py``). Drop the script's own directory and expose the
# package parent instead, so the standard library wins.
_HERE = Path(__file__).resolve().parent
_TOOLS_DIR = _HERE.parent
sys.path = [p for p in sys.path if not p or Path(p).resolve() != _HERE]
if str(_TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLS_DIR))

from music_authoring.inspect import (  # noqa: E402
    InspectError,
    build_inspect_document,
    load_audio_preview,
    render_html,
    serialize_embedded_json,
)
from music_authoring.lower import build_review_payload, lower  # noqa: E402
from music_authoring.score import Diagnostic, TOOL_NAME, TOOL_VERSION  # noqa: E402
from music_authoring.validate import load_and_validate  # noqa: E402

PLAYER_ASSETS = Path(__file__).resolve().parent / "library_player"
LIBRARY_PAYLOAD = "atmlib-library-player"
LIBRARY_PAYLOAD_VERSION = 1
CATALOG_FORMAT = "atmlib-song-library-catalog"
PLAYER_TOOL_NAME = "atm-music-library"
PLAYER_VERSION = "1.0.0"

REPO_ROOT = Path(__file__).resolve().parents[2]

GENERATED_NOTE = (
    "Generated by tools/music_authoring/library_player.py from "
    "examples/music_authoring/catalog.json. Every song below is embedded in full "
    "(canonical review document + matching AVR WAV); the page opens offline with "
    "no server, network or build directory."
)


class LibraryError(Exception):
    """Structured bundler failure carrying a diagnostic code."""

    def __init__(self, code: str, message: str, suggestion: str, exit_code: int = 3, path: str = ""):
        super().__init__(message)
        self.code = code
        self.message = message
        self.suggestion = suggestion
        self.exit_code = exit_code
        self.path = path

    def diagnostic(self) -> dict:
        return Diagnostic(self.code, self.path, self.message, self.suggestion).as_dict()


def _read_asset(name: str) -> str:
    return (PLAYER_ASSETS / name).read_text(encoding="utf-8")


def _catalog_relative(root: Path, ref: str) -> str:
    """Keep the authored, repo-root-relative path form.

    The canonical review payload records the *given* source path string, and the
    ``inspect`` snapshot embeds the relative form.  The bundler runs with the
    repository root as the working directory and passes the catalog's own
    relative path straight through, so the bundled document is byte-identical to
    the ``inspect`` snapshot (and never leaks a machine-absolute path).
    """
    path = Path(ref)
    if path.is_absolute():
        try:
            return path.resolve().relative_to(root).as_posix()
        except ValueError:
            return ref
    return Path(ref).as_posix()


def load_catalog(catalog_path: Path) -> dict:
    if not catalog_path.is_file():
        raise LibraryError(
            "CATALOG_MISSING",
            f"catalog {catalog_path} not found",
            "Pass --catalog pointing at an atmlib-song-library-catalog JSON file.",
            exit_code=3,
            path="/catalog",
        )
    try:
        data = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise LibraryError(
            "CATALOG_INVALID",
            f"cannot read catalog {catalog_path}: {exc}",
            "Fix the JSON syntax.",
            exit_code=2,
            path="/catalog",
        ) from exc
    if data.get("format") != CATALOG_FORMAT:
        raise LibraryError(
            "CATALOG_INVALID",
            f"catalog format is {data.get('format')!r}, expected {CATALOG_FORMAT!r}",
            "Set \"format\" to atmlib-song-library-catalog.",
            exit_code=2,
            path="/format",
        )
    entries = data.get("entries")
    if not isinstance(entries, list) or not entries:
        raise LibraryError(
            "CATALOG_INVALID",
            "catalog has no entries",
            "Add at least one entry with id/name/category/source/preview.",
            exit_code=2,
            path="/entries",
        )
    return data


def build_entry(raw: dict, root: Path, index: int) -> dict:
    """Rebuild one canonical review document and package it for embedding."""
    where = f"/entries/{index}"
    for key in ("id", "name", "source"):
        if not isinstance(raw.get(key), str) or not raw.get(key):
            raise LibraryError(
                "CATALOG_INVALID",
                f"entry {index} is missing a string {key!r}",
                f"Add {key!r} to the catalog entry.",
                exit_code=2,
                path=f"{where}/{key}",
            )

    source_ref = _catalog_relative(root, raw["source"])
    if "folder" in raw and (not isinstance(raw["folder"], str) or not raw["folder"].strip()):
        raise LibraryError(
            "CATALOG_INVALID",
            f"entry {raw['id']!r} folder must be a nonempty string",
            "Set folder to a folder name, or omit it to use the category.",
            exit_code=2,
            path=f"{where}/folder",
        )
    preview_ref_raw = raw.get("preview") or raw.get("render")
    if not isinstance(preview_ref_raw, str) or not preview_ref_raw:
        raise LibraryError(
            "CATALOG_INVALID",
            f"entry {raw['id']!r} is missing a 'preview' directory",
            "Add 'preview' (a directory with preview.json + preview.wav).",
            exit_code=2,
            path=f"{where}/preview",
        )
    preview_ref = _catalog_relative(root, preview_ref_raw)

    score, diagnostics = load_and_validate(source_ref)
    if score is None:
        code = 3 if any(d.code == "IO_ERROR" for d in diagnostics) else 2
        first = diagnostics[0] if diagnostics else None
        raise LibraryError(
            first.code if first else "SOURCE_INVALID",
            f"cannot validate {raw['id']!r}: {first.message if first else 'invalid score'}",
            first.suggestion if first else "Fix the score source.",
            exit_code=code,
            path=f"{where}/source",
        )

    lowered = lower(score)
    review_payload = build_review_payload(score, lowered)

    try:
        audio, audio_diagnostics = load_audio_preview(preview_ref, review_payload)
    except InspectError as exc:
        raise LibraryError(
            "AUDIO_PREVIEW_INVALID",
            f"entry {raw['id']!r} audio preview failed: {exc.message}",
            exc.suggestion,
            exit_code=exc.exit_code,
            path=f"{where}/preview",
        ) from exc
    if audio is None:
        detail = audio_diagnostics[0].message if audio_diagnostics else "no matching preview"
        raise LibraryError(
            "AUDIO_PREVIEW_MISSING",
            f"entry {raw['id']!r} has no matching audio preview: {detail}",
            "Render the WAV with `atm-music render` and keep preview.json + preview.wav together.",
            exit_code=3,
            path=f"{where}/preview",
        )

    document = build_inspect_document(
        review_payload=review_payload,
        score_id=score.id,
        audio=audio,
        audio_diagnostics=audio_diagnostics,
    )
    html = render_html(document)

    clock = document["review"].get("clock") or {}
    entry = {
        "id": raw["id"],
        "name": raw["name"],
        "category": raw.get("category") or "",
        "folder": raw.get("folder") or raw.get("category") or "Other",
        "context": raw.get("context") or "",
        "score_id": score.id,
        "source": source_ref,
        "source_sha256": document.get("source_sha256"),
        "event_digest_hex": document.get("event_digest_hex"),
        "total_ticks": document["review"].get("total_ticks"),
        "effective_bpm": clock.get("effective_bpm"),
        "song_seconds": audio.get("song_seconds"),
        "wav_sha256": audio.get("wav_sha256"),
        "wav_bytes": audio.get("wav_bytes"),
        "sample_count": audio.get("sample_count"),
        "html": html,
        "html_bytes": len(html.encode("utf-8")),
        "audio_diagnostics": [d.as_dict() for d in audio_diagnostics],
    }
    return entry


def render_player(catalog: dict, root: Path) -> tuple[str, list[dict]]:
    entries = [build_entry(raw, root, i) for i, raw in enumerate(catalog["entries"])]
    bundle = {
        "payload": LIBRARY_PAYLOAD,
        "payload_version": LIBRARY_PAYLOAD_VERSION,
        "tool": {"name": PLAYER_TOOL_NAME, "version": PLAYER_VERSION},
        "frontend": {"name": TOOL_NAME, "version": TOOL_VERSION},
        "note": GENERATED_NOTE,
        "entries": entries,
    }
    template = _read_asset("template.html")
    html = (
        template.replace("__ATMLIB_PLAYER_CSS__", _read_asset("shell.css"), 1)
        .replace("__ATMLIB_LIBRARY__", serialize_embedded_json(bundle), 1)
        .replace("__ATMLIB_PLAYER_JS__", _read_asset("shell.js"), 1)
    )
    return html, entries


def run(
    *,
    catalog_path: str,
    out_path: str,
    report_path: str | None = None,
    root: str | None = None,
) -> tuple[dict, int]:
    root_path = Path(root).resolve() if root else REPO_ROOT
    catalog_abs = Path(catalog_path)
    if not catalog_abs.is_absolute():
        catalog_abs = (Path.cwd() / catalog_abs).resolve()
    out_abs = Path(out_path)
    if not out_abs.is_absolute():
        out_abs = (Path.cwd() / out_abs).resolve()
    report_abs = None
    if report_path:
        report_abs = Path(report_path)
        if not report_abs.is_absolute():
            report_abs = (Path.cwd() / report_abs).resolve()

    prev_cwd = Path.cwd()
    try:
        # Validate/lower with the repository root as the working directory so the
        # catalog's relative paths resolve and the canonical review payload keeps
        # the relative source path form the inspect snapshots use.
        os.chdir(root_path)
        catalog = load_catalog(catalog_abs)
        html, entries = render_player(catalog, root_path)
    except LibraryError as exc:
        return ({"ok": False, "diagnostics": [exc.diagnostic()], "artifacts": {}}, exc.exit_code)
    finally:
        os.chdir(prev_cwd)

    out = out_abs
    if out.exists() and out.is_dir():
        return (
            {
                "ok": False,
                "diagnostics": [
                    Diagnostic("IO_ERROR", "", f"--out {out_path!r} is a directory", "Pass a file path.").as_dict()
                ],
                "artifacts": {},
            },
            3,
        )

    html_bytes = html.encode("utf-8")
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(html_bytes)
    except OSError as exc:
        return (
            {
                "ok": False,
                "diagnostics": [
                    Diagnostic("IO_ERROR", "", f"cannot write {out}: {exc}", "Check paths and permissions.").as_dict()
                ],
                "artifacts": {},
            },
            3,
        )

    report = {
        "schema_version": 1,
        "player": str(out),
        "player_sha256": hashlib.sha256(html_bytes).hexdigest(),
        "player_bytes": len(html_bytes),
        "catalog": str(catalog_abs),
        "tool": {"name": PLAYER_TOOL_NAME, "version": PLAYER_VERSION},
        "frontend": {"name": TOOL_NAME, "version": TOOL_VERSION},
        "song_count": len(entries),
        "songs": [
            {
                "id": e["id"],
                "name": e["name"],
                "category": e["category"],
                "folder": e["folder"],
                "score_id": e["score_id"],
                "source": e["source"],
                "source_sha256": e["source_sha256"],
                "event_digest_hex": e["event_digest_hex"],
                "wav_sha256": e["wav_sha256"],
                "wav_bytes": e["wav_bytes"],
                "embedded_html_bytes": e["html_bytes"],
            }
            for e in entries
        ],
    }

    artifacts = {"player": str(out)}
    if report_abs:
        rp = report_abs
        try:
            rp.parent.mkdir(parents=True, exist_ok=True)
            rp.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
            artifacts["report"] = str(rp)
        except OSError as exc:
            return (
                {
                    "ok": False,
                    "diagnostics": [
                        Diagnostic("IO_ERROR", "", f"cannot write report {rp}: {exc}", "Check paths.").as_dict()
                    ],
                    "artifacts": {},
                },
                3,
            )

    return ({"ok": True, "diagnostics": [], "artifacts": artifacts, "report": report}, 0)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="atm-music-library",
        description="Bundle every catalogued example song into one offline library player.html.",
    )
    parser.add_argument("--catalog", default=str(REPO_ROOT / "examples/music_authoring/catalog.json"))
    parser.add_argument("--out", default=str(REPO_ROOT / "examples/music_authoring/player.html"))
    parser.add_argument("--report", default=None, help="Optional path for a machine-readable bundle report.")
    parser.add_argument("--root", default=None, help="Base directory for relative source/preview paths (default: repo root).")
    parser.add_argument("--json", action="store_true", help="Ignored; stdout is always one JSON document.")
    args = parser.parse_args(argv)

    payload, code = run(
        catalog_path=args.catalog,
        out_path=args.out,
        report_path=args.report,
        root=args.root,
    )
    print(json.dumps(payload, ensure_ascii=True, sort_keys=False))
    if not payload.get("ok"):
        for item in payload.get("diagnostics", []):
            print(f"{item['code']}: {item['message']}", file=sys.stderr)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
